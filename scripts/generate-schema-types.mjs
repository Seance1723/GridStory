import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { componentManifests, pageSchema } from '../packages/example-kit/dist/manifests.js';
import { generateTypeScriptContracts } from '../packages/schema/dist/typegen.js';

const target = resolve('packages/example-kit/src/generated.ts');
const output = generateTypeScriptContracts([pageSchema], componentManifests, {
  banner: '/* Generated by `pnpm schema:generate`. Do not edit directly. */',
});
const mode = process.argv[2] ?? '--check';

if (mode === '--write') {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, output, 'utf8');
  console.log(`Generated ${target}.`);
} else if (mode === '--check') {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== output) {
    console.error('Generated schema contracts are stale. Run `pnpm schema:generate`.');
    process.exitCode = 1;
  } else {
    console.log('Generated schema contracts match the canonical source IR.');
  }
} else {
  throw new Error(`Unknown schema generation mode ${mode}.`);
}
